/// One known app: bundle id, display name, launch URL scheme ("" when none is
/// known), rarity code (g gold, c covert, k classified, r restricted,
/// m mil-spec) and a fallback SF Symbol for when the real icon is unavailable.
struct CatalogApp {
    let bundleID: String
    let name: String
    let scheme: String
    let rarity: String
    let symbol: String

    init(_ bundleID: String, _ name: String, _ scheme: String, _ rarity: String, _ symbol: String) {
        self.bundleID = bundleID
        self.name = name
        self.scheme = scheme
        self.rarity = rarity
        self.symbol = symbol
    }
}

