"""Turns a device app dump (from compare_with_device.py) into catalog entries
with launch URL schemes, and rewrites the URL-scheme allow-list in Info.plist.

Why: on a non-jailbroken iPhone the only dependable way for App Unboxed to see
whether a third-party app is installed is canOpenURL on that app's URL scheme,
and the scheme has to be listed in Info.plist ahead of time. This script
harvests real schemes from a connected phone so those apps become detectable
(and launchable) on every phone.

Usage:  python scripts/build_scheme_catalog.py [device_dump.json]

Run it with no argument to reset to the public default (no extra entries).
The output lists the apps on the phone the dump came from, so do not
commit a generated src/AppCatalogExtra.swift or Info.plist to a public repo.
"""
import io, json, os, plistlib, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
SWIFT_OUT = os.path.join(ROOT, "src", "AppCatalogExtra.swift")
CURATED = os.path.join(ROOT, "src", "AppCatalog.swift")
PLIST = os.path.join(ROOT, "Resources", "Info.plist")

BAD_PREFIX = ("fb", "com.googleusercontent", "com.google.sso", "msauth", "amzn-", "appcenter-", "exp+",
              "db-", "aw", "wx", "wb", "ms-xal", "tincan", "pwv", "ydl", "eos.", "brooklyn", "hac8", "lkz", "helo",
              "sbux", "qbu", "qb0", "www.", "aonic", "instagram-", "vnd.")
BAD_EXACT = {"http", "https", "prefs", "bitcoin", "otpauth", "totp", "neighborhoods", "apollourl", "testvpn"}


GENERIC = {"http", "https", "prefs", "bitcoin", "otpauth", "totp", "msauth", "truesdk", "apollourl", "file",
           "mailto", "tel", "sms", "itms-apps", "ethereum", "wc", "lightning", "upi", "testvpn"}


def pick_scheme(name, schemes):
    """Prefer a clean, name-like scheme; fall back to any scheme unique to the
    app (fb<id>, com.googleusercontent..., etc. still prove the app is there)."""
    key = re.sub(r"[^a-z0-9]", "", name.lower())
    usable = [s for s in schemes if s and s.lower() not in GENERIC and re.fullmatch(r"[A-Za-z][A-Za-z0-9+.\-]*", s)]
    if not usable:
        return ""
    def score(s):
        k = re.sub(r"[^a-z0-9]", "", s.lower())
        ugly = s.lower() in BAD_EXACT or s.lower().startswith(BAD_PREFIX)
        return (ugly, 0 if k == key else 1 if (k in key or key in k) else 2, "." in s, len(s))
    return sorted(usable, key=score)[0]


def rarity(bid):
    n = 0
    for ch in bid:
        n = (n * 31 + ord(ch)) % 1000
    n %= 100
    return "m" if n < 46 else "r" if n < 74 else "k" if n < 90 else "c" if n < 98 else "g"


def main():
    # With no dump the generated file is an empty stub: the public default.
    dump = json.load(io.open(sys.argv[1], encoding="utf-8")) if len(sys.argv) > 1 else {"apps": {}}
    curated_src = io.open(CURATED, encoding="utf-8").read()
    curated_ids = set(re.findall(r'CatalogApp\("([^"]+)"', curated_src))
    pairs = [(b, s) for b, s in re.findall(r'CatalogApp\("([^"]+)", "[^"]*", "([^"]*)"', curated_src) if s]
    curated_scheme_ids = [b for b, s in pairs]
    curated_schemes = [s for b, s in pairs]

    curated_empty = set(re.findall(r'CatalogApp\("([^"]+)", "[^"]*", ""', curated_src))
    overrides = {}
    rows = []
    for bid, app in sorted(dump["apps"].items(), key=lambda kv: kv[1]["name"].lower()):
        if app["type"] != "User" or bid.startswith("com.appunboxed"):
            continue
        if bid in curated_ids:
            if bid in curated_empty:
                sch = pick_scheme(app["name"], app["schemes"])
                if sch:
                    overrides[bid] = sch
            continue
        scheme = pick_scheme(app["name"], dump["apps"][bid]["schemes"])
        rows.append((bid, app["name"].replace('"', "'"), scheme))

    lines = ["import Foundation", "",
             "// Generated by scripts/build_scheme_catalog.py. Empty in the public repo;",
             "// run the script against your own phone to add its apps for a personal build.",
             "// Each entry carries the app's own URL scheme, which is what lets a",
             "// non-jailbroken phone detect (and open) it.",
             "extension AppCatalog {", "    static let extra: [CatalogApp] = ["]
    for bid, name, scheme in rows:
        s = scheme + "://" if scheme else ""
        lines.append(f'        CatalogApp("{bid}", "{name}", "{s}", "{rarity(bid)}", "app.fill"),')
    lines += ["    ]", "", "    /// Schemes for hand-curated entries that were listed without one."]
    if overrides:
        lines.append("    static let extraSchemes: [String: String] = [")
        for bid, sch in sorted(overrides.items()):
            lines.append(f'        "{bid}": "{sch}://",')
        lines.append("    ]")
    else:
        # Swift needs [:] for an empty dictionary literal.
        lines.append("    static let extraSchemes: [String: String] = [:]")
    lines += ["}", ""]
    io.open(SWIFT_OUT, "w", encoding="utf-8", newline="\n").write("\n".join(lines))

    # Info.plist allow-list: keep the existing order (iOS may only honour the
    # first 50), then every other scheme the catalogs know.
    with open(PLIST, "rb") as f:
        text = f.read().decode("utf-8")
    plist = plistlib.loads(text.encode("utf-8"))
    # On iOS 15+ SDK stamps only the first 50 entries are honoured, so the
    # most widely installed third-party apps go first. Apple's own apps are
    # found another way and go last.
    top = """twitter instagram snssdk1233 youtube snapchat discord spotify reddit fb fb-messenger whatsapp tg nflx
             twitch googlechrome googlegmail comgooglemaps google roblox minecraft clashofclans clashroyale brawlstars
             chatgpt steammobile com.amazon.mobile.shopping paypal venmo cashme uber ubereats doordash youtubemusic
             disneyplus hulu aiv barcelona pinterest codm pokemongo FortniteClient xbox kick xai-grok Life360
             mcdmobileapp starbucks ms-outlook zoomus duolingo""".split()
    ordered = list(top)
    seen = {s.lower() for s in ordered}
    apple_last = [c.split(":")[0] for c, b in zip(curated_schemes, curated_scheme_ids) if b.startswith("com.apple.")]
    third = [c.split(":")[0] for c, b in zip(curated_schemes, curated_scheme_ids) if not b.startswith("com.apple.")]
    for s in third + list(overrides.values()) + [r[2] for r in rows if r[2]] + apple_last:
        if s and s.lower() not in seen and s.lower() not in ("http", "https", "app-settings"):
            ordered.append(s)
            seen.add(s.lower())
    i = text.index("<key>LSApplicationQueriesSchemes</key>")
    j = text.index("</array>", i) + len("</array>")
    block = "<key>LSApplicationQueriesSchemes</key>\n\t<array>\n" + "".join(f"\t\t<string>{s}</string>\n" for s in ordered) + "\t</array>"
    io.open(PLIST, "w", encoding="utf-8", newline="").write(text[:i] + block + text[j:])
    plistlib.load(open(PLIST, "rb"))
    print(f"extra catalog entries: {len(rows)} ({sum(1 for r in rows if r[2])} with a scheme); "
          f"curated schemes filled in: {len(overrides)}; plist schemes: {len(ordered)}")
    print("no scheme at all:", ", ".join(r[1].encode("ascii", "replace").decode() for r in rows if not r[2]))


if __name__ == "__main__":
    main()
